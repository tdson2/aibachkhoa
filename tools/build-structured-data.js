// ---------------------------------------------------------------- helpers

const read = (rel) => fs.readFileSync(path.join(PUBLIC, rel), 'utf8');

function meta(html, re) {
    const m = html.match(re);
    return m ? m[1] : null;
}

const descOf = (html) => meta(html, /<meta name="description" content="([^"]*)"/);
const canonOf = (html) => meta(html, /<link rel="canonical" href="([^"]*)"/);
const imageOf = (html) => meta(html, /<meta property="og:image" content="([^"]*)"/);

function crumbs(items) {
    return {
        '@type': 'BreadcrumbList',
        itemListElement: items.map((it, i) => ({
            '@type': 'ListItem',
            position: i + 1,
            name: it.name,
            item: it.url
        }))
    };
}

function appNode(html, { name, type, category, genre, os, offers, sameAs }) {
    const node = {
        '@type': type,
        name,
        url: canonOf(html),
        description: descOf(html),
        operatingSystem: os,
        offers,
        publisher: { '@id': ORG['@id'] },
        author: { '@id': ORG['@id'] }
    };
    if (type === 'VideoGame') {
        node.applicationCategory = 'GameApplication';
        if (genre) node.genre = genre;
        node.gamePlatform = os;
    } else if (category) {
        node.applicationCategory = category;
    }
    const img = imageOf(html);
    if (img) node.image = img;
    if (sameAs && sameAs.length) node.sameAs = sameAs;
    return node;
}

function write(rel, graph) {
    const file = path.join(PUBLIC, rel);
    let html = fs.readFileSync(file, 'utf8');

    // Drop a previously generated block so re-running is idempotent.
    html = html.replace(
        /\n    <!-- structured data \(generated by tools\/build-structured-data\.js\) -->\n    <script type="application\/ld\+json">[\s\S]*?<\/script>/,
        ''
    );

    const json = JSON.stringify({ '@context': 'https://schema.org', '@graph': graph }, null, 4)
        .split('\n').map(l => '    ' + l).join('\n');
    const block = `\n${OPEN}\n    <script type="application/ld+json">\n${json}\n    </script>`;

    if (!html.includes('</head>')) throw new Error(`no </head> in ${rel}`);
    html = html.replace('\n</head>', `${block}\n</head>`);
    fs.writeFileSync(file, html);
}

